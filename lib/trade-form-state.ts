export function buildFormFromQuickLog(
  quick: QuickLogState,
  options?: { dailyBias?: string; accountId?: string; captures?: TradeCapture[] },
): Record<string, unknown> {
  const entry = Number(quick.entryPrice) || 0;
  const exit = Number(quick.exitPrice) || 0;
  const sl = Number(quick.stopLossPrice) || 0;
  const size = Number(quick.positionSize) || 1;
  const commission = Number(quick.commission) || 0;
  const pnl =
    entry && exit
      ? calculatePnlPreview(entry, exit, quick.direction, size, commission)
      : null;
  const rr = entry && sl && exit ? calculateRiskReward(entry, sl, exit, quick.direction) : null;
  const slPips = entry && sl ? calculateStopLossPips(entry, sl, quick.instrument) : null;

  const screenshotIds = options?.captures?.map((c) => c.storageId) ?? [];

  return getDefaultFormState({
    accountId: options?.accountId ?? "",
    instrument: quick.instrument,
    direction: quick.direction,
    session: quick.session,
    environment: quick.environment,
    entryPrice: quick.entryPrice,
    exitPrice: quick.exitPrice,
    stopLossPrice: quick.stopLossPrice,
    positionSize: quick.positionSize,
    commission: quick.commission,
    riskAmount: quick.riskAmount,
    whyEntered: quick.whyEntered,
    winLossStatus: quick.winLossStatus,
    dailyBias: options?.dailyBias ?? "NEUTRAL",
    pnl: pnl !== null ? String(pnl) : "",
    finalRR: rr !== null ? String(rr) : "",
    stopLossPips: slPips !== null ? String(slPips) : "5",
    target1RR: rr !== null ? String(Math.max(rr, 1)) : "3",
    tradeClosureReason: quick.exitPrice ? "MANUAL_EXIT" : "OPEN",
    screenshots: screenshotIds,
  });
}

