export function quickLogToPayload(
  quick: QuickLogState,
  options?: { dailyBias?: string; accountId?: Id<"accounts">; captures?: TradeCapture[] },
): Record<string, unknown> {
  const form = buildFormFromQuickLog(quick, {
    dailyBias: options?.dailyBias,
    accountId: options?.accountId ? String(options.accountId) : undefined,
    captures: options?.captures,
  });
  return formToTradePayload(form, options?.captures);
}
